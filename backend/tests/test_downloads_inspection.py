def test_every_app_csp_lets_the_page_frame_its_own_blob_pdf():
    """The wizard previews by framing a blob: URL. The app's
    Content-Security-Policy lives in the nginx template, repeated
    per location (add_header inheritance), and its frame-src must
    name blob: — without it the browser refuses the frame and the
    visitor sees a broken-document icon where the form should be
    (the API bytes were always fine; curl can't see CSP). The
    files-origin policy is a different, deliberately minimal one
    (frame-ancestors only) and is out of this test's scope."""
    import re
    from pathlib import Path

    template = (
        Path(__file__).resolve().parents[2]
        / "frontend"
        / "nginx.conf.template"
    ).read_text()
    policies = re.findall(r'add_header Content-Security-Policy "([^"]+)"', template)
    app_policies = [p for p in policies if "default-src" in p]
    assert len(app_policies) >= 4, "the app block repeats its CSP per location"
    for policy in app_policies:
        frame_src = re.search(r"frame-src ([^;]+);", policy)
        assert frame_src is not None, policy
        assert "blob:" in frame_src.group(1).split(), policy
