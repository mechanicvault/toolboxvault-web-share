"""The customizable vehicle inspection checklist (owner order
2026-11-09): the inspection row's Customize wizard, backed by
public generate endpoints.

Proves:
- the options payload carries the nine wizard categories with
  every item, in the visitor's language, and every line of the
  static checklist the shelf used to hand out is in the catalog
  (an untouched wizard reproduces the full sheet);
- the preview generates a real PDF from the posted choices —
  shop header in, deselected categories out — and moves NO
  download counter;
- the download serves the generated bytes and moves the
  inspection row's count by exactly one;
- an unknown item key is an honest 400 and counts nothing;
- everything works signed-out (these calls carry no auth).
"""

