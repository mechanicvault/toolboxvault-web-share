# ------------------------------------------------------------------
# The wallpaper shelf (Downloads Part 3, owner order 2026-11-08)
# ------------------------------------------------------------------
# One artwork, three device files: desktop / tablet / mobile,
# each cropped to its device's aspect from the one base piece.
# A wallpaper's three sizes are three rows in download_files —
# the counted download path (/files/{key}) serves them exactly
# like documents — keyed "<artwork>-<size>". The artwork itself
# is the catalog unit the Wallpaper tab lists: its count is the
# sum of its sizes' counts, and the per-size counts ride along
# (the tab shows the artwork's total; the preview shows each
# size's own number).
#
# The artwork was made in-house for this shelf (generated
# in-lane, eyeball-reviewed piece by piece; the branded half
# wears the site's genuine logo artwork, composited onto the
# scenes programmatically — never generator-rendered text).
# Titles and descriptions are dictionary copy
# (downloads.wallpaper.<key>.name/.desc), like the documents.

WALLPAPER_SIZES: tuple[str, ...] = ("desktop", "tablet", "mobile")

# The honest pixel dimensions of each size, labelled as such
# in the gallery: desktop 16:9, tablet 3:4, phone ~19.5:9.
WALLPAPER_SIZE_DIMS: dict[str, tuple[int, int]] = {
    "desktop": (2560, 1440),
    "tablet": (2048, 2732),
    "mobile": (1170, 2532),
}


# The wallpaper categories (Sweep E2, owner order via
# BUSY-WORK #4): every piece carries exactly one. Branded
# (Toolbox Vault-themed) pieces live in Abstract.
WALLPAPER_CATEGORIES: tuple[str, ...] = (
    "cars",
    "tools",
    "engines",
    "abstract",
    "high-tech",
)


@dataclass(frozen=True)
class WallpaperEntry:
    key: str
    """The artwork's slug — the view URL segment and the
    dictionary stem. Its download rows are "<key>-<size>"."""
    title_slug: str
    """Title-Case stem for the saved-as filenames."""
    branded: bool
    """True when the piece carries Toolbox Vault branding as
    its main theme (the branded shelf section)."""
    category: str
    """Exactly one of WALLPAPER_CATEGORIES (Sweep E2)."""
    sort_order: int

    def size_entry(self, size: str) -> CatalogEntry:
        return CatalogEntry(
            key=f"{self.key}-{size}",
            packaged=f"wallpapers/{self.key}-{size}.jpg",
            filename=(
                f"Toolbox-Vault-{self.title_slug}-{size.capitalize()}.jpg"
            ),
            file_format="jpg",
            sort_order=self.sort_order,
        )

    def size_entries(self) -> tuple[CatalogEntry, ...]:
        return tuple(self.size_entry(size) for size in WALLPAPER_SIZES)


def _wp(
    key: str, title_slug: str, branded: bool, category: str, sort_order: int
) -> WallpaperEntry:
    if category not in WALLPAPER_CATEGORIES:
        raise ValueError(f"unknown wallpaper category {category!r}")
    return WallpaperEntry(
        key=key,
        title_slug=title_slug,
        branded=branded,
        category=category,
        sort_order=sort_order,
    )


