"""The downloads catalog — the files the /downloads page hands
out (owner order 2026-11-08: the bare door became a real page
with a Documents tab; Part 3 added the wallpaper shelf below —
one artwork, three device-sized files, same counted path).

This list is the ONE definition of the shelf: the migration
seeds the download_files rows from it, the service upserts any
row a deploy is missing, and the files themselves live as
packaged bytes in files/ (generated by generate_assets.py; the
inventory sheet is the production capture of the sheet the old
page served). The storage service carries the same bytes under
downloads/<packaged filename> — the service seeds storage from
the package on first use, so the shelf works the same in every
environment.

Titles and descriptions are NOT here: they are interface copy
and live in the frontend dictionary (downloads.file.<key>.*),
translated EN/ES like everything else on the page.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class CatalogEntry:
    key: str
    """Stable public key — the URL segment and the i18n key stem."""
    packaged: str
    """The file's name inside files/ (and its storage key tail)."""
    filename: str
    """The friendly name the visitor's browser saves it as."""
    file_format: str
    """'xlsx' or 'pdf' — the list's Format column."""
    sort_order: int


