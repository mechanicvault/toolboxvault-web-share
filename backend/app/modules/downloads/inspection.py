ITEM_KEYS: frozenset[str] = frozenset(
    item.key for category in CATEGORIES for item in category.items
)

TOTAL_ITEMS = len(ITEM_KEYS)


def options_payload(lang: str) -> dict:
    """The wizard's data: every category with its items, named
    in the visitor's language. All items start ON client-side —
    an untouched wizard reproduces the full checklist."""
    lang = clamp_lang(lang)
    return {
        "categories": [
            {
                "key": category.key,
                "name": category.names[lang],
                "items": [
                    {"key": item.key, "label": item.labels[lang]}
                    for item in category.items
                ],
            }
            for category in CATEGORIES
        ]
    }


def resolve_selection(item_keys: list[str] | None) -> set[str]:
    """Validate the posted selection. None means untouched —
    everything on. An unknown key is a client error, not a
    silent drop."""
    if item_keys is None:
        return set(ITEM_KEYS)
    unknown = [key for key in item_keys if key not in ITEM_KEYS]
    if unknown:
        raise ValueError(f"Unknown inspection item: {unknown[0]}")
    return set(item_keys)


