"""The customizable vehicle inspection checklist (owner order
2026-11-09): the Documents shelf's inspection row stops being a
plain download. Its button is Customize, opening a popup wizard —
shop info first (all optional, brands the PDF header), then one
screen per category with every item toggleable — and the system
generates the PDF from the visitor's choices for preview and
download.

The item catalog lives HERE, code-defined and bilingual like the
prints categories: item labels are data, so the generated PDF
follows the language the visitor is browsing in. The base is the
static checklist the shelf has always handed out (all 33 of its
lines are here, some re-homed to the category they belong to),
expanded with standard multi-point items where that sheet was
thin. Every item defaults ON, so an untouched wizard reproduces
the full checklist (plus any shop branding the visitor typed).

Generation is per-request from the posted choices with the same
fpdf2 machinery and navy form design as the static documents —
never a stored file. The preview endpoint generates WITHOUT
counting; the download endpoint counts through the shelf's own
machinery (service.record_download against the inspection row)
and only then serves the generated bytes.
"""

