def build_inspection_pdf(
    *,
    selected: set[str],
    lang: str = "en",
    shop_name: str = "",
    shop_address: str = "",
    shop_phone: str = "",
) -> bytes:
    """Render the customized checklist. Shop info is optional:
    whatever the visitor gave brands the header, above the
    vehicle fields. Only the selected categories/items print;
    the Recommended Work table, Notes and sign-off are the
    form's working furniture and always ride along (the same
    blocks the static sheet ends with)."""
    from app.core import docframe

    lang = clamp_lang(lang)
    text = _TEXT[lang]
    cls = docframe.framed_pdf_class()
    pdf = cls(orientation="P", unit="mm", format="Letter")
    pdf.frame_chrome = docframe.CHROME[lang]
    pdf.frame_when = date.today()
    pdf.core_fonts_encoding = "cp1252"
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(12, 12, 12)
    pdf.add_page()
    pdf.frame_header(text["title"], None)

    shop_name = (shop_name or "").strip()
    shop_address = (shop_address or "").strip()
    shop_phone = (shop_phone or "").strip()
    if shop_name or shop_address or shop_phone:
        pdf.ln(3)
        if shop_name:
            pdf.set_font("helvetica", "B", 14)
            pdf.set_text_color(*ga.NAVY)
            pdf.cell(0, 7, ga._safe(shop_name), new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(0, 0, 0)
        pdf.set_font("helvetica", "", 9.5)
        for line in (shop_address, shop_phone):
            if line:
                pdf.cell(0, 5, ga._safe(line), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)
    else:
        pdf.ln(4)

    ga._field_row(pdf, text["fields1"])
    ga._field_row(pdf, text["fields2"])
    ga._field_row(pdf, text["fields3"])
    pdf.set_font("helvetica", "I", 9)
    pdf.cell(0, 5, ga._safe(text["mark_note"]), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    for category in CATEGORIES:
        chosen = [item for item in category.items if item.key in selected]
        if not chosen:
            continue
        ga._section(pdf, category.names[lang].upper())
        for item in chosen:
            ga._check_item(pdf, item.labels[lang], text["options"])
        pdf.ln(1.5)

    ga._section(pdf, text["recommended"])
    ga._table_head(pdf, text["rec_cols"])
    ga._table_rows(pdf, text["rec_cols"], 6)
    ga._section(pdf, text["notes"])
    ga._write_lines(pdf, 8)
    ga._field_row(pdf, text["signoff"])
    return bytes(pdf.output())
