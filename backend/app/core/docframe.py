"""The ONE document frame (Ryan, 2026-11-05 — standing rule).

Every document the site generates wears the same top and the
same bottom; only the guts change. The frame is modeled on
Ryan's own inventory report from the app (the format benchmark,
saved at ~/workspace/user/files/inventory-report-20261105-231638.pdf
and measured element by element):

  TOP (first page only)
    - the document title, centered, bold caps (Helvetica 22,
      slate ink #1e293b), shrunk only as far as a long title
      forces;
    - "Prepared {MM/DD/YYYY}" centered under it (10pt, slate
      grey #64748b);
    - a bordered PREPARED FOR box spanning the content width:
      the label (bold 7.5pt, steel blue #2f5d8a), the name
      (bold 12pt), and the address lines on the left; "Phone:" /
      "Email:" right-aligned on the right. Fields the owner
      never set are simply ABSENT — no blank lines, no dangling
      labels (the prepared-for rule every renderer already
      followed).
  BOTTOM (every page)
    - the Toolbox Vault WORDMARK — the sliced brand image,
      never typed text, never redrawn — centered horizontally,
      7mm tall, flanked by "Generated by" on its left and
      "· {MM/DD/YYYY} · Page {N}" on its right (8pt, #999).
      Page N only: the model carries no total.

Colors, sizes and offsets below are the model's measured
geometry (Letter original; the frame centers on whatever page
size the document itself uses — page size is a property of the
document, not of the frame).

The wordmark bytes are the repo's one in-backend copy
(backend/app/modules/downloads/assets/wordmark-transparent.png,
byte-identical to the brand master — the downloads sheet pins
that identity) so every generator embeds the same file.

Frame labels resolve in the generating user's language
(EN/ES — the activity reports' chrome precedent, audit A17);
dates are the model's MM/DD/YYYY in both.
"""

from datetime import date
from pathlib import Path

WORDMARK_PATH = (
    Path(__file__).resolve().parent.parent
    / "modules"
    / "downloads"
    / "assets"
    / "wordmark-transparent.png"
)
_WORDMARK_W_PX = 2115
_WORDMARK_H_PX = 312

# The model's measured palette.
INK = (30, 41, 59)  # #1e293b — title, name
GREY = (100, 116, 139)  # #64748b — prepared line, phone/email
LABEL_BLUE = (47, 93, 138)  # #2f5d8a — the PREPARED FOR label
BODY = (51, 65, 85)  # #334155 — address lines
BOX_BORDER = (176, 190, 205)  # the model's light slate box rule
FOOTER_GREY = (153, 153, 153)  # #999999 — footer texts

# The report layout standard's body palette (Ryan, 2026-11-06 —
# files/report-layout-standard-2026-11-06.md): the navy of the
# element-4 banner and the element-7 totals bars, and the faint
# grey hairline that follows every body row (element 6) — a
# whisper on paper, never the bold black rule of the old tables.
NAVY = (0, 43, 92)
ROW_LINE = (205, 205, 205)
ROW_LINE_WIDTH = 0.15

WORDMARK_H_MM = 7.0
WORDMARK_W_MM = WORDMARK_H_MM * _WORDMARK_W_PX / _WORDMARK_H_PX  # ≈ 47.4mm
_FOOTER_IMG_FROM_BOTTOM = 12.2  # image top sits this far above the page foot
_FOOTER_GAP = 2.5  # between the wordmark and its flanking texts

CHROME = {
    "en": {
        "prepared": "Prepared {when}",
        "prepared_for": "PREPARED FOR",
        "phone": "Phone",
        "email": "Email",
        "generated_by": "Generated by",
        "page": "Page",
        "dealer": "DEALER",
        "agent": "AGENT",
    },
    "es": {
        "prepared": "Preparado el {when}",
        "prepared_for": "PREPARADO PARA",
        "phone": "Teléfono",
        "email": "Correo",
        "generated_by": "Generado por",
        "page": "Página",
        "dealer": "DISTRIBUIDOR",
        "agent": "AGENTE",
    },
}


def chrome_for(owner) -> dict:
    """Frame labels in the generating user's language."""
    from app.core.i18n import resolve_locale

    return CHROME[resolve_locale(owner)]


def _safe(text) -> str:
    """Fold onto the cp1252 the framed documents render in
    (each generator sets core_fonts_encoding='cp1252'): the
    typographic characters fold to stand-ins, anything still
    unrepresentable folds rather than failing the render."""
    text = str(text or "")
    text = (
        text.replace("—", "-")
        .replace("–", "-")
        .replace("…", "...")
        .replace("“", '"')
        .replace("”", '"')
        .replace("‘", "'")
        .replace("’", "'")
    )
    return text.encode("cp1252", errors="replace").decode("cp1252")


def _model_date(when: date) -> str:
    return when.strftime("%m/%d/%Y")


_wordmark_stream_cache: dict = {}


def _wordmark_stream():
    """The wordmark bytes to embed: the master PNG normalized
    once through PIL to the width the frame actually prints
    (47mm ≈ 560px at 300dpi; 1024px keeps retina headroom).
    The master file is 2115px and ~1.3MB — embedding it raw
    would fatten every generated document by that much for no
    visible gain. Cached per process; None if unreadable (the
    footer then prints its texts without the image rather than
    failing the document)."""
    if "stream" not in _wordmark_stream_cache:
        stream = None
        try:
            import io

            from PIL import Image

            image = Image.open(WORDMARK_PATH).convert("RGBA")
            if image.width > 1024:
                image.thumbnail((1024, 1024))
            buffer = io.BytesIO()
            image.save(buffer, "PNG")
            stream = buffer.getvalue()
        except Exception:
            stream = None
        _wordmark_stream_cache["stream"] = stream
    return _wordmark_stream_cache["stream"]


def draw_frame_footer(pdf, chrome: dict, when: date) -> None:
    """The model's bottom: wordmark centered, generated-by on
    its left, date + page on its right. Called from footer(),
    so it lands on EVERY page including the first."""
    page_w, page_h = pdf.w, pdf.h
    img_w, img_h = WORDMARK_W_MM, WORDMARK_H_MM
    img_x = (page_w - img_w) / 2
    # Measured on the model: the image's top edge sits 12.2mm
    # above the page foot (7.05mm of image + ~5.2mm of margin).
    img_y = page_h - _FOOTER_IMG_FROM_BOTTOM
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(*FOOTER_GREY)
    text_y = img_y + 2.0
    left = _safe(chrome["generated_by"])
    left_w = pdf.get_string_width(left) + 1
    pdf.set_xy(img_x - _FOOTER_GAP - left_w, text_y)
    pdf.cell(left_w, 2.8, left, align="R")
    right = _safe(
        f"· {_model_date(when)} · {chrome['page']} {pdf.page_no()}"
    )
    pdf.set_xy(img_x + img_w + _FOOTER_GAP, text_y)
    pdf.cell(pdf.get_string_width(right) + 1, 2.8, right)
    stream = _wordmark_stream()
    if stream is not None:
        import io

        pdf.image(io.BytesIO(stream), x=img_x, y=img_y, w=img_w, h=img_h)
    pdf.set_text_color(0, 0, 0)


def draw_frame_header(
    pdf,
    *,
    title: str,
    prepared_for: dict | None,
    chrome: dict,
    when: date,
    parties: dict | None = None,
) -> None:
    """The model's top, drawn at the current position (the top
    margin of page 1). Leaves the cursor at the left margin,
    just under the prepared-for box (or under the prepared line
    when there is no prepared-for block to show).

    `parties` (truck statement, owner markup 2026-11-06): a
    document whose header box must ALSO name the other parties
    passes {"dealer": {...}, "agent": {...}} — fact dicts with
    any of name/phone/email. The box then reads in two labeled
    columns: PREPARED FOR on the left WITH its phone/email
    under the address (a fact with no value omits its label —
    never a dangling empty label), and the DEALER / AGENT
    blocks on the right, each fact labeled, nothing
    overlapping. Absent (every other document), the box is the
    model's exactly: right side = the prepared-for's own
    phone/email, right-aligned."""
    usable = pdf.w - pdf.l_margin - pdf.r_margin
    x0 = pdf.l_margin
    y = pdf.get_y()

    # Title — centered bold caps; shrink only until it fits.
    size = 22.0
    text = _safe(title).upper()
    pdf.set_text_color(*INK)
    while size > 12:
        pdf.set_font("helvetica", "B", size)
        if pdf.get_string_width(text) <= usable - 2:
            break
        size -= 1.0
    pdf.set_xy(x0, y)
    pdf.cell(usable, 11, text, align="C", new_x="LMARGIN", new_y="NEXT")

    # Prepared date — centered, grey.
    pdf.set_font("helvetica", "", 10)
    pdf.set_text_color(*GREY)
    pdf.cell(
        usable,
        5.5,
        _safe(chrome["prepared"].format(when=_model_date(when))),
        align="C",
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.set_text_color(0, 0, 0)

    prepared = prepared_for or {}
    name = (prepared.get("name") or "").strip()
    address_lines = [
        line.strip()
        for line in (prepared.get("address") or "").splitlines()
        if line.strip()
    ]
    phone = (prepared.get("phone") or "").strip()
    email = (prepared.get("email") or "").strip()

    # Party blocks (statement header): normalized to the blocks
    # that carry at least a name or one fact — an empty block
    # never prints, and inside a block a missing fact never
    # prints its label.
    party_blocks: list[tuple[str, dict]] = []
    for key in ("dealer", "agent"):
        facts = (parties or {}).get(key) or {}
        clean = {
            f: (facts.get(f) or "").strip() for f in ("name", "phone", "email")
        }
        if any(clean.values()):
            party_blocks.append((key, clean))
    if not (name or address_lines or phone or email or party_blocks):
        pdf.set_xy(x0, pdf.get_y() + 1)
        return

    # The prepared-for box.
    pad = 3.5
    label_h, name_h, line_h = 3.8, 6.2, 4.7
    party_name_h, party_gap = 5.6, 2.4
    left_h = label_h + (name_h if name else 0) + line_h * len(address_lines)
    right_lines = []
    if party_blocks:
        # The prepared-for's own phone/email move UNDER its
        # address on the left; the right side belongs to the
        # party blocks.
        left_h += line_h * ((1 if phone else 0) + (1 if email else 0))
        right_h = 0.0
        for _key, facts in party_blocks:
            block_h = label_h + (party_name_h if facts["name"] else 0)
            block_h += line_h * (
                (1 if facts["phone"] else 0) + (1 if facts["email"] else 0)
            )
            right_h += block_h
        right_h += party_gap * (len(party_blocks) - 1)
    else:
        if phone:
            right_lines.append(f"{chrome['phone']}: {phone}")
        if email:
            right_lines.append(f"{chrome['email']}: {email}")
        right_h = line_h * len(right_lines)
    box_y = pdf.get_y() + 3.5
    box_h = pad * 2 + max(left_h, right_h)

    pdf.set_draw_color(*BOX_BORDER)
    pdf.set_line_width(0.25)
    # Rounded like the model's — a round clip over a plain rect
    # (fpdf2 2.8 has no public rounded rect); square if the clip
    # is ever unavailable.
    try:
        with pdf.round_clip(x0, box_y, usable, box_h, 1.8):
            pdf.rect(x0, box_y, usable, box_h, style="D")
    except Exception:
        pdf.rect(x0, box_y, usable, box_h, style="D")

    # Two-column geometry only while party blocks ride: the
    # left column keeps the prepared-for, the right column
    # starts just past the middle. Without parties the left
    # column spans the box as it always has.
    left_w = usable * 0.52 - pad if party_blocks else usable - pad * 2
    cy = box_y + pad
    pdf.set_xy(x0 + pad, cy)
    pdf.set_font("helvetica", "B", 7.5)
    pdf.set_text_color(*LABEL_BLUE)
    pdf.cell(left_w, label_h, _safe(chrome["prepared_for"]))
    cy += label_h
    if name:
        pdf.set_xy(x0 + pad, cy)
        pdf.set_font("helvetica", "B", 12)
        pdf.set_text_color(*INK)
        pdf.cell(left_w, name_h, _safe(name))
        cy += name_h
    pdf.set_font("helvetica", "", 9.3)
    pdf.set_text_color(*BODY)
    for line in address_lines:
        pdf.set_xy(x0 + pad, cy)
        pdf.cell(left_w, line_h, _safe(line))
        cy += line_h
    if party_blocks:
        pdf.set_text_color(*GREY)
        if phone:
            pdf.set_xy(x0 + pad, cy)
            pdf.cell(left_w, line_h, _safe(f"{chrome['phone']}: {phone}"))
            cy += line_h
        if email:
            pdf.set_xy(x0 + pad, cy)
            pdf.cell(left_w, line_h, _safe(f"{chrome['email']}: {email}"))
            cy += line_h

    if party_blocks:
        right_x = x0 + usable * 0.52
        right_w = usable - usable * 0.52 - pad
        ry = box_y + pad
        for i, (key, facts) in enumerate(party_blocks):
            if i:
                ry += party_gap
            label = chrome.get(key) or key.capitalize()
            pdf.set_xy(right_x, ry)
            pdf.set_font("helvetica", "B", 7.5)
            pdf.set_text_color(*LABEL_BLUE)
            pdf.cell(right_w, label_h, _safe(f"{label}:"))
            ry += label_h
            if facts["name"]:
                # Shrink only as far as a long name forces, the
                # title's own rule — a party name never spills
                # out of its column.
                size = 11.0
                pdf.set_text_color(*INK)
                while size > 8.5:
                    pdf.set_font("helvetica", "B", size)
                    if pdf.get_string_width(_safe(facts["name"])) <= right_w:
                        break
                    size -= 0.5
                pdf.set_xy(right_x, ry)
                pdf.cell(right_w, party_name_h, _safe(facts["name"]))
                ry += party_name_h
            pdf.set_font("helvetica", "", 9.3)
            pdf.set_text_color(*GREY)
            if facts["phone"]:
                pdf.set_xy(right_x, ry)
                pdf.cell(
                    right_w, line_h, _safe(f"{chrome['phone']}: {facts['phone']}")
                )
                ry += line_h
            if facts["email"]:
                pdf.set_xy(right_x, ry)
                pdf.cell(
                    right_w, line_h, _safe(f"{chrome['email']}: {facts['email']}")
                )
                ry += line_h
    else:
        ry = box_y + pad
        pdf.set_font("helvetica", "", 9.3)
        pdf.set_text_color(*GREY)
        for line in right_lines:
            pdf.set_xy(x0 + pad, ry)
            pdf.cell(usable - pad * 2, line_h, _safe(line), align="R")
            ry += line_h
    pdf.set_text_color(0, 0, 0)
    pdf.set_draw_color(0, 0, 0)
    pdf.set_xy(x0, box_y + box_h)


class FramePDF:
    """An FPDF mixin carrying the frame: footer() draws the
    model's bottom on every page; frame_header() draws the top
    once. Generators subclass their FPDF with this mixin and set
    frame_chrome / frame_when (defaults: EN, today)."""

    frame_chrome: dict = CHROME["en"]
    frame_when: date = date.today()

    def footer(self):  # noqa: D102 — fpdf2 hook
        draw_frame_footer(self, self.frame_chrome, self.frame_when)

    def frame_header(
        self,
        title: str,
        prepared_for: dict | None,
        parties: dict | None = None,
    ) -> None:
        draw_frame_header(
            self,
            title=title,
            prepared_for=prepared_for,
            chrome=self.frame_chrome,
            when=self.frame_when,
            parties=parties,
        )


def framed_pdf_class():
    """A ready FPDF subclass carrying the frame, for generators
    that instantiate FPDF directly. Built lazily so importing
    this module never drags fpdf2 into unrelated core imports."""
    from fpdf import FPDF

    class FramedFPDF(FramePDF, FPDF):
        pass

    return FramedFPDF
